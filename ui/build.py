"""Build ui/index.html: inline susp.js and the preset designs into app.html (one self-contained file)."""
import glob
import json
import re
import os
import sys
here = os.path.dirname(os.path.abspath(__file__))
root = os.path.dirname(here)
sys.path.insert(0, root)

# Only the public example designs in designs/ are built into the page. Team designs stay in private/ (git-ignored)
# and are opened in the page with "Open JSON".
presets = []
for path in sorted(glob.glob(os.path.join(root, "designs", "*.json"))) + sorted(glob.glob(os.path.join(root, "designs", "case_study", "*.json"))):
    with open(path) as f:
        cfg = json.load(f)
    presets.append({"label": cfg.get("name") or os.path.basename(path), "cfg": cfg})
if not presets:
    sys.exit("no designs/*.json found")
html = open(os.path.join(here, "app.html")).read()
# team settings (encrypted with the team passphrase; see ui/src/03_team.js): team/settings.enc if the repo has one
_tp = os.path.join(root, "team", "settings.enc")
team_enc = json.dumps(json.load(open(_tp)), separators=(",", ":")) if os.path.exists(_tp) else "null"
# The page is assembled from src/: style.css and the numbered JS modules, which run in order inside one closure
# (they share helpers such as $, fmt, cfg and ev). Edit the files in src/, then run this script.
src = os.path.join(here, "src")
css = open(os.path.join(src, "style.css")).read()
mods = sorted(f for f in os.listdir(src) if f.endswith(".js"))
app_js = "(function () {\n" + "".join(open(os.path.join(src, f)).read() for f in mods) + "})();"
html = html.replace("/*CSS*/", css.rstrip("\n"), 1).replace("/*APP_JS*/", app_js, 1)
glossary = open(os.path.join(here, "glossary.js")).read()
cad = open(os.path.join(here, "cad.js")).read()
# the shared schema (schema/*.json, also read by the Python solver), as window.SUSP_SCHEMA for susp.js
schema = {n: json.load(open(os.path.join(root, "schema", n + ".json"))) for n in ("defaults", "metrics", "targets", "points", "moves")}
schema["rules"] = {f[:-5]: json.load(open(os.path.join(root, "schema", "rules", f))) for f in sorted(os.listdir(os.path.join(root, "schema", "rules"))) if f.endswith(".json")}
# the solver: ui/solver/*.js, in file-name order, inside one closure (the same shape as ui/src/). Also written to
# ui/susp.js (generated, not committed) for the Node tests and anyone who wants the solver on its own.
sdir = os.path.join(here, "solver")
solver = ('/* susp.js - FSAE double-wishbone solver (browser port of the Python `susp` package). GENERATED by ui/build.py\n'
          '   from ui/solver/*.js - edit those. Same conventions: X forward, Y outboard, Z up, mm, deg, N; right-hand wheel;\n'
          '   ground at Z = 0. Every function mirrors a Python function of the same name; tests/test_parity.py compares them. */\n'
          '(function (root) {\n  "use strict";\n'
          + "".join(open(os.path.join(sdir, f)).read() for f in sorted(os.listdir(sdir)) if f.endswith(".js"))
          + '})(typeof window !== "undefined" ? window : globalThis);\n')
with open(os.path.join(here, "susp.js"), "w") as f:
    f.write(solver)
js = "window.SUSP_SCHEMA = " + json.dumps(schema, ensure_ascii=False, separators=(",", ":")) + ";\n" + solver
html = html.replace("/*SUSP_JS*/", js).replace("/*CAD_JS*/", cad).replace("/*GLOSSARY_JS*/", glossary).replace("/*PRESETS*/", json.dumps(presets)).replace("/*APP_VERSION*/", json.dumps(re.search(r'^version = "([^"]+)"', open(os.path.join(root, "pyproject.toml")).read(), re.M).group(1))).replace("/*TEAM_ENC*/", team_enc).replace("/*SW_MACRO*/", json.dumps(open(os.path.join(root, "tools", "solidworks", "ExportHardpoints.bas"), encoding="utf-8").read()).replace("</", "<\\/"))
# third-party code and fonts, built in so the page works offline (from a USB stick): ui/vendor/ (see its README)
import base64  # noqa: E402
vend = os.path.join(here, "vendor")
FONTS = [("Barlow Condensed", w, f"barlow-condensed-latin-{w}-normal.woff2") for w in (500, 600, 700)] + \
        [("IBM Plex Mono", w, f"ibm-plex-mono-latin-{w}-normal.woff2") for w in (400, 500)] + \
        [("IBM Plex Sans", w, f"ibm-plex-sans-latin-{w}-normal.woff2") for w in (400, 500, 600)]
fonts_css = "".join(
    f"@font-face{{font-family:'{fam}';font-style:normal;font-weight:{w};font-display:swap;"
    f"src:url(data:font/woff2;base64,{base64.b64encode(open(os.path.join(vend, 'fonts', fn), 'rb').read()).decode()}) format('woff2')}}\n"
    for fam, w, fn in FONTS)


def lib(name):
    return open(os.path.join(vend, name), encoding="utf-8").read().replace("</script", "<\\/script")


html = html.replace("/*FONTS_CSS*/", fonts_css.rstrip("\n"), 1).replace("/*THREE_JS*/", lib("three.min.js"), 1).replace("/*XLSX_JS*/", lib("xlsx.full.min.js"), 1)
SITE = "https://sunfish-labs.github.io/fsae-suspension-solver/ui/"
local_html = html.replace("/*GUIDE_URL*/", "guide.html")
html = html.replace("/*GUIDE_URL*/", SITE + "guide.html")   # the hosted Claude page links to the public guide
# artifact version: page content only (the publisher adds the document skeleton)
with open(os.path.join(here, "artifact.html"), "w") as f:
    f.write(html)
# standalone version for double-clicking from the folder: full HTML document
doc = ('<!doctype html>\n<html lang="en">\n<head>\n<meta charset="utf-8">\n'
       '<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">\n'
       '<style>body{margin:0}</style>\n</head>\n<body>\n' + local_html + '\n</body>\n</html>\n')
with open(os.path.join(here, "index.html"), "w") as f:
    f.write(doc)
print(f"wrote ui/index.html and ui/artifact.html ({len(html) // 1024} KB)")
